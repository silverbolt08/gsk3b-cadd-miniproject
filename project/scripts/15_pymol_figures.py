"""
Stage 6 - render the candidate binding modes in PyMOL.

Generates one .pml script per compound and runs it through headless PyMOL
(ray-traced). The interactions drawn are not PyMOL's own guesses: the
endpoints come straight from 06_analysis/plip/interaction_geometry.json, so
the dashed lines in the figure are exactly the contacts PLIP reported and
the report quotes. Residue labels are converted to UniProt numbering
(model number + 34).

The .pml files are kept in 06_analysis/figures/pymol/ so the figures can be
regenerated or edited by hand in the PyMOL GUI.

Usage: python 15_pymol_figures.py LIG068:fig10_tofacitinib LIG093:fig11_hesperetin ...
"""
import json, os, subprocess, sys
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, ".."))
CPX = os.path.join(ROOT, "06_analysis", "complexes")
PLIPDIR = os.path.join(ROOT, "06_analysis", "plip")
FIG = os.path.join(ROOT, "06_analysis", "figures")
PML = os.path.join(FIG, "pymol")
OFFSET = 34

# dash colours per interaction type, matching the report's key
COLORS = {"hbond": ("hb", "0.184, 0.435, 0.816"),
          "hydrophobic": ("hyd", "0.604, 0.627, 0.651"),
          "pistacking": ("pis", "0.184, 0.561, 0.435"),
          "saltbridge": ("salt", "0.851, 0.514, 0.141"),
          "pication": ("pic", "0.541, 0.310, 0.753"),
          "waterbridge": ("wat", "0.098, 0.655, 0.784"),
          "halogen": ("hal", "0.753, 0.310, 0.627")}

HEADER = """# PyMOL script - {name} in the GSK-3beta ATP site
# generated by scripts/15_pymol_figures.py; interactions from PLIP
reinitialize
bg_color white
set ray_opaque_background, 1
set antialias, 2
set ray_shadows, 0
set ray_trace_mode, 0
set specular, 0.15
set ambient, 0.28
set direct, 0.55
set cartoon_transparency, 0.55
set cartoon_fancy_helices, 1
set stick_radius, 0.11
set label_size, 16
set label_color, black
set label_font_id, 7
set label_outline_color, white
set dash_gap, 0.30
set dash_width, 2.2
set dash_round_ends, 0
set transparency_mode, 2

load {pdb}, cx
hide everything
show cartoon, cx and polymer
color grey80, cx and polymer
"""


def residue_labels(pdb_path, resnums):
    """CB (or CA) coordinate of each contacting residue, for the label anchor"""
    out = {}
    for line in open(pdb_path):
        if not line.startswith("ATOM"):
            continue
        num = int(line[22:26])
        if num not in resnums:
            continue
        name = line[12:16].strip()
        if name in ("CB", "CA"):
            out.setdefault(num, {})[name] = line[17:20].strip()
    return out


def residue_anchor_coords(pdb_path, resnums):
    """CB (else CA) coordinate per contacting residue, for the label anchor"""
    out, fallback = {}, {}
    for line in open(pdb_path):
        if not line.startswith("ATOM"):
            continue
        num = int(line[22:26])
        if num not in resnums:
            continue
        xyz = np.array([float(line[30:38]), float(line[38:46]), float(line[46:54])])
        name = line[12:16].strip()
        if name == "CB":
            out[num] = xyz
        elif name == "CA":
            fallback[num] = xyz
    for num, xyz in fallback.items():
        out.setdefault(num, xyz)
    return out


def ligand_coords(pdb_path):
    return np.array([[float(l[30:38]), float(l[38:46]), float(l[46:54])]
                     for l in open(pdb_path)
                     if l.startswith("HETATM") and l[17:20].strip() == "LIG"])


def build_pml(lig_id, figname, receptor="model"):
    geom = json.load(open(os.path.join(PLIPDIR, "interaction_geometry.json")))
    g = geom[lig_id]
    pdb = os.path.join(CPX, f"{lig_id}_{receptor}_complex.pdb").replace("\\", "/")

    contacts = {}
    for it in g["interactions"]:
        label = it["res"]
        num = int("".join(c for c in label if c.isdigit()))
        contacts[num - OFFSET] = label
    resi = "+".join(str(n) for n in sorted(contacts))

    lines = [HEADER.format(name=g["name"], pdb=pdb)]
    lines.append(f"select contacts, cx and polymer and resi {resi}")
    lines.append("show sticks, contacts and not (name C+N+O and not resn PRO)")
    lines.append("color grey55, contacts and elem C")
    lines.append("select lig, cx and resn LIG")
    lines.append("show sticks, lig")
    lines.append("set stick_radius, 0.19, lig")
    lines.append("color cyan, lig and elem C")
    lines.append("select nearwat, cx and resn HOH within 5 of lig")
    lines.append("show spheres, nearwat and elem O")
    lines.append("set sphere_scale, 0.22, nearwat")
    lines.append("color deepteal, nearwat")
    lines.append("util.cnc('lig or contacts')")
    lines.append("hide everything, (hydro and (elem H and neighbor elem C))")

    # interactions, drawn from the PLIP geometry via pseudoatoms
    for i, it in enumerate(g["interactions"]):
        tag, rgb = COLORS.get(it["kind"], ("oth", "0.4, 0.4, 0.4"))
        a, b = it["p1"], it["p2"]
        lines.append(f"pseudoatom p{i}a, pos=[{a[0]}, {a[1]}, {a[2]}]")
        lines.append(f"pseudoatom p{i}b, pos=[{b[0]}, {b[1]}, {b[2]}]")
        lines.append(f"distance {tag}_{i}, p{i}a, p{i}b")
        lines.append(f"set_color c_{tag}_{i}, [{rgb}]")
        lines.append(f"set dash_color, c_{tag}_{i}, {tag}_{i}")
        lines.append(f"hide labels, {tag}_{i}")
        lines.append(f"hide everything, p{i}a p{i}b")

    # residue labels in UniProt numbering
    coords = residue_anchor_coords(
        os.path.join(CPX, f"{lig_id}_{receptor}_complex.pdb"), set(contacts))
    lig_xyz = ligand_coords(os.path.join(CPX, f"{lig_id}_{receptor}_complex.pdb"))
    centre = lig_xyz.mean(axis=0)
    for num, text in sorted(contacts.items()):
        if num not in coords:
            continue
        p = coords[num]
        v = p - centre
        p = p + 2.2 * v / (np.linalg.norm(v) + 1e-6)
        pretty = text[:3].title() + text[3:]
        lines.append(f"pseudoatom lab{num}, pos=[{p[0]:.2f}, {p[1]:.2f}, {p[2]:.2f}], "
                     f'label="{pretty}"')

    lines += [
        "orient lig",
        "zoom lig, 4.5",
        "turn x, -8",
        "set field_of_view, 22",
        f"png {os.path.join(FIG, figname + '.png').replace(chr(92), '/')}, "
        "width=1800, height=1250, dpi=300, ray=1",
    ]
    os.makedirs(PML, exist_ok=True)
    path = os.path.join(PML, f"{figname}.pml")
    open(path, "w").write("\n".join(lines) + "\n")
    return path


def run(pml):
    exe = os.path.join(os.path.expanduser("~"), "AppData", "Roaming", "Python",
                       f"Python{sys.version_info.major}{sys.version_info.minor}",
                       "Scripts", "pymol.exe")
    cmd = [exe, "-cq", pml] if os.path.exists(exe) else \
          [sys.executable, "-m", "pymol", "-cq", pml]
    r = subprocess.run(cmd, capture_output=True, text=True, timeout=900)
    return r.returncode, (r.stdout + r.stderr)[-500:]


def main():
    jobs = [a.split(":") for a in sys.argv[1:]] or [
        ["LIG068", "fig10_tofacitinib"],
        ["LIG093", "fig11_hesperetin"],
        ["LIG084", "fig12_luteolin"],
    ]
    for lig_id, figname in jobs:
        pml = build_pml(lig_id, figname)
        rc, out = run(pml)
        png = os.path.join(FIG, figname + ".png")
        size = os.path.getsize(png) if os.path.exists(png) else 0
        print(f"  {lig_id} -> {figname}.png  rc={rc}  {size/1e3:.0f} kB")
        if not size:
            print("   ", out)


if __name__ == "__main__":
    main()
